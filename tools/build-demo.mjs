/**
 * Build the no-dependency classic entry so file:// demos need no module loader.
 * Source modules remain the editable implementation; bundled data is generated.
 */
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {resolve} from 'node:path';
import {validateResearchPackage} from '../js/research-library.js';
import {checkReleaseLibraries} from './release-policy.mjs';
import {documentPages} from './build-docs.mjs';
import {buildIcons} from './build-icons.mjs';

const root = new URL('../',import.meta.url);
const read = path => readFile(new URL(path,root),'utf8').then(value=>value.replace(/^\uFEFF/,'').replace(/\r\n/g,'\n'));
const json = async path => JSON.parse(await read(path));
async function indexed(path,key) {
    const manifest=await json(path);
    return Promise.all(manifest[key].map(async entry=> {
        const url=new URL(entry,new URL(path,root));
        if (!fileURLToPath(url).startsWith(fileURLToPath(root))) throw new Error('Index path must stay inside project: '+entry);
        return JSON.parse((await readFile(url,'utf8')).replace(/^\uFEFF/,''));
    }));
}
export async function buildEntry() {
    await checkReleaseLibraries(root);
    const defaultResearch=await json('packs/guide-pack.json');
    const validation=validateResearchPackage(defaultResearch);
    if(!validation.isValid)throw new Error(validation.errors.join(' '));
    const data={profiles:await indexed('data/library.json','profiles'),snapshots:await indexed('data/startup-library.json','snapshots')};
    const modules=['js/validator.js','js/research-library.js','js/context.js','js/tasks.js','js/matching.js','js/evaluation.js','js/recommendation.js','js/explanations.js','js/analyzer.js','js/storage.js','js/ui.js','js/app.js'];
    const bodies=await Promise.all(modules.map(async path=>{
        const source=(await read(path))
            .replace(/^import \{[^\n]+\} from '[^']+';\r?$/gm,'')
            .replace(/^export \{[^\n]+\} from '[^']+';\r?$/gm,'')
            .replace(/^export /gm,'')
            .replaceAll('import.meta.url','APP_SCRIPT_URL');
        if (/^import |^export /m.test(source)) throw new Error('Unsupported module declaration in '+path);
        return '// '+path+'\n'+source;
    }));
    const bundle='// Generated by node tools/build-demo.mjs. Edit js source modules, then rebuild.\n'+
        '(() => {\n"use strict";\nconst APP_SCRIPT_URL = document.currentScript.src;\n'+
        'const __DEFAULT_RESEARCH__ = '+JSON.stringify(defaultResearch)+';\n'+
        'const __PACKAGED_DATA__ = '+JSON.stringify(data)+';\n'+bodies.join('\n\n')+'\n})();\n';
    const shell=(await read('index.html'))
        .replace(/src="js\/app\.bundle\.js(?:\?v=[^"]+)?"/,'src="js/app.bundle.js"')
        .replace(/href="css\/style\.css(?:\?v=[^"]+)?"/,'href="css/style.css"');
    const documents=await documentPages(root);
    const hash=createHash('sha256')
        .update(bundle).update(shell).update(await read('css/style.css')).update(await read('manifest.json'))
        .update(await read('LICENSE')).update(await read('DATA_LICENSE.md'))
        .update(await read('README.md')).update(await read('DEVELOPMENT.md')).update(await read('assets/how-it-works.svg'))
        .update(await read('assets/methodology.svg'))
        .update(documents.map(document=>document.html).join('\n'))
        .update(await readFile(new URL('icons/icon-192.png',root))).update(await readFile(new URL('icons/icon-512.png',root)))
        .digest('hex').slice(0,12);
    return {bundle,hash};
}
export async function buildFiles() {
    await buildIcons(root);
    const {bundle,hash}=await buildEntry();
    await writeFile(new URL('js/app.bundle.js',root),bundle);
    const html=(await read('index.html'))
        .replace(/src="js\/app\.bundle\.js(?:\?v=[^"]+)?"/,'src="js/app.bundle.js?v='+hash+'"')
        .replace(/href="css\/style\.css(?:\?v=[^"]+)?"/,'href="css/style.css?v='+hash+'"');
    await writeFile(new URL('index.html',root),html);
    for(const document of await documentPages(root)) {
        await mkdir(new URL('./',new URL(document.path,root)),{recursive:true});
        await writeFile(new URL(document.path,root),document.html.replace('href="../css/style.css"','href="../css/style.css?v='+hash+'"'));
    }
    const worker=(await read('sw.js'))
        .replace(/const CACHE_NAME = '[^']+';/,"const CACHE_NAME = 'founder-gap-"+hash+"';")
        .replace(/^  '\.\/js\/(?:app|analyzer|ui|storage|validator)\.js',\r?\n/gm,'')
        .replace(/^  '\.\/js\/app\.bundle\.js(?:\?v=[^']+)?',\r?\n/gm,'')
        .replace(/^  '\.\/css\/style\.css(?:\?v=[^']+)?',\r?\n/gm,"  './css/style.css?v="+hash+"',\n  './js/app.bundle.js?v="+hash+"',\n");
    await writeFile(new URL('sw.js',root),worker);
    return hash;
}
if (process.argv[1] && resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
    console.log('Built local demo '+await buildFiles());
}
